// ไกด์ชื่อในป๊อปอัปเลือกชื่อ (เช่น จากระบบจองเวร) — ใช้ได้ทั้งฝั่งเซิร์ฟเวอร์และหน้าเว็บ
export interface GuideItem {
  /** ชื่อที่จะใส่ลงตาราง (จับคู่กับรายชื่อในตารางแล้ว) */
  name: string;
  /** ชื่อ-นามสกุลตามระบบจอง */
  booked: string;
  /** ช่วงเวลาที่จอง */
  slot?: string;
  /** หมายเหตุการจับคู่ชื่อ */
  note?: string;
  /** ส่วนของตารางที่คนนี้จองไว้ (ตาราง 3 ช่วงเวลา: "1" | "2" | "3") — คลิกแล้วใส่ในตารางช่วงอื่นที่จองไว้ด้วย */
  secs?: string[];
}
export interface BookingGuide {
  /** คอลัมน์ที่แสดงไกด์ ("*" = ทุกคอลัมน์ที่เลือกชื่อได้) */
  cols: string[];
  /** ส่วนของตาราง (เช่น "1" | "2" | "3" ของตาราง 3 ช่วงเวลา) — ไม่ระบุ = ทุกส่วน */
  sec?: string;
  /** แสดงเฉพาะช่องที่ยังว่าง */
  onlyEmpty?: boolean;
  title: string;
  /** วันที่ (1–31) → รายชื่อที่จอง */
  byDay: Record<number, GuideItem[]>;
  error?: string;
}
