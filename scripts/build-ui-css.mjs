// สร้างไฟล์ CSS ของ UI (Tailwind v4 + daisyUI v5) แบบคอมไพล์ล่วงหน้า แล้ว commit ไฟล์ผลลัพธ์ src/app/ui.css
// ไม่ต้องติดตั้งแพ็กเกจเพิ่มบน Vercel — ตารางเวร (.sheet) และ PDF ไม่ได้ใช้ไฟล์นี้
// ใช้: TW_DIR=<path ของ tailwindcss v4> DAISY=<path ของ daisyui.mjs> ESBUILD=<path ของ esbuild> node scripts/build-ui-css.mjs
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const TW_DIR = process.env.TW_DIR || "/opt/npm-tools/node_modules/tailwindcss";
const DAISY = process.env.DAISY;
const ESBUILD = process.env.ESBUILD || "/opt/npm-tools/node_modules/esbuild";
const tw = await import(pathToFileURL(path.join(TW_DIR, "dist/lib.mjs")).href);
const daisy = (await import(pathToFileURL(DAISY).href)).default;

const input = fs.readFileSync(path.join(root, "src/styles/ui.src.css"), "utf8");
const compiler = await tw.compile(input, {
  base: path.join(root, "src/styles"),
  async loadStylesheet(id, base) {
    let p;
    if (id.startsWith("tailwindcss")) {
      const rest = id.replace(/^tailwindcss\/?/, "") || "index.css";
      p = path.join(TW_DIR, rest.endsWith(".css") ? rest : rest + ".css");
    } else p = path.resolve(base, id);
    return { path: p, base: path.dirname(p), content: fs.readFileSync(p, "utf8") };
  },
  async loadModule(id, base) {
    if (id === "daisyui") return { path: DAISY, base: path.dirname(DAISY), module: daisy };
    if (id === "daisyui/theme") {
      const m = (await import(pathToFileURL(path.join(path.dirname(DAISY), "daisyui-theme.mjs")).href)).default;
      return { path: DAISY, base: path.dirname(DAISY), module: m };
    }
    throw new Error("unknown module " + id);
  },
});

// เก็บ candidate จากไฟล์ .tsx/.ts ใน src/components และ src/app
const files = [];
const walk = (d) => { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); if (f.isDirectory()) walk(p); else if (/\.(tsx|ts)$/.test(f.name)) files.push(p); } };
walk(path.join(root, "src/components")); walk(path.join(root, "src/app"));
const cands = new Set();
for (const f of files) {
  const s = fs.readFileSync(f, "utf8");
  for (const m of s.matchAll(/[^\s"'`{}()<>;,=]+/g)) { const t = m[0].replace(/^[\[]+|[\]]+$/g, ""); if (t.length < 80) cands.add(t); }
}
let css = compiler.build([...cands]);
const require = createRequire(import.meta.url);
const esbuild = require(ESBUILD);
const out = await esbuild.transform(css, { loader: "css", minify: true, target: ["chrome100", "safari15", "firefox100"] });
const header = "/* generated by scripts/build-ui-css.mjs — อย่าแก้ไฟล์นี้โดยตรง ให้แก้ src/styles/ui.src.css แล้วรันใหม่ */\n";
fs.writeFileSync(path.join(root, "src/app/ui.css"), header + out.code);
console.log("ui.css", out.code.length, "bytes,", cands.size, "candidates", out.warnings.length, "warnings");
